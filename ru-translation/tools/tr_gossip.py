_MISPLACED = re.compile(r"^I seem to have misplaced my (.+)\. Can you help\?$")
_SURE = re.compile(r"^Are you sure, that you want to go to (.+)\?$")


def translate_option(t):
    if t in T:
        return T[t]
    if t in PLACES:
        return PLACES[t]
    m = _MISPLACED.match(t)
    if m and m.group(1) in ITEMS:
        return f"Кажется, я потерял {ITEMS[m.group(1)]}. Поможешь?"
    return None


