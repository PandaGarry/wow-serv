--===========================================================================
-- Admin Tools RU — Tab_Server.lua
-- Вкладка «Сервер»: информация, обслуживание, игроки и доступ, сообщения.
--===========================================================================

local p = AT.RegisterTab("Сервер")

--===========================================================================
-- Информация
--===========================================================================
local y = AT.MakeSection(p, "Информация", -2)

y = AT.FlowButtons(p, {
	{ "Инфо сервера",  ".server info",  AT.BTN_W, 1, "Версия, аптайм, число игроков" },
	{ "GPS",           ".gps",          AT.BTN_W, 1, "Координаты и карта" },
	{ "Мой аккаунт",   ".account",      AT.BTN_W, 1, "Информация об аккаунте" },
	{ "Кто онлайн",    ".who",          AT.BTN_W, 1, "Список игроков в мире" },
	{ "ГМы в игре",    ".gm ingame",    AT.BTN_W, 1, "ГМы, находящиеся в игре" },
	{ "Все ГМы",       ".gm list",      AT.BTN_W, 1, "Все ГМы и их уровни" },
}, y)

--===========================================================================
-- Игроки и доступ
--===========================================================================
y = AT.MakeSection(p, "Игроки и доступ", y - 6)

y = AT.FlowButtons(p, {
	{ "Кикнуть",  ".kick",   AT.BTN_W, 2, "Кикнуть игрока (укажи ник в поле ниже)" },
	{ "Мут",      ".mute",   AT.BTN_W, 3, "Заглушить игрока" },
	{ "Размут",   ".unmute", AT.BTN_W, 3, "Снять блокировку чата" },
	{ "Забанить персонажа", function()
		AT.Print("Сначала введи ник в поле «Управление игроком» ниже.")
	end, AT.BTN_W, 3, "Бан персонажа — поле ниже" },
	{ "Список банов", ".ban list", AT.BTN_W, 3, "Все активные баны" },
}, y)

y = AT.FormRow(p, y - 4, "Управление игроком (ник):", function(t)
	-- готовим всё для кнопок бана/кика по этому нику
	AT.lastPlayerInput = t
	return ".pinfo " .. t
end)

y = AT.FlowButtons(p, {
	{ "Кикнуть ник", function()
		AT.ConfirmCmd(".kick " .. (AT.lastPlayerInput or "ник"), "Кикнуть игрока?")
	end, AT.BTN_W, 2, "Кикнуть игрока из поля выше" },
	{ "Бан персонажа", function()
		AT.ConfirmCmd(".ban character " .. (AT.lastPlayerInput or "ник") .. " 30 Забанен администратором",
			"Забанить персонажа на 30 дней?")
	end, AT.BTN_W, 3, "Бан персонажа на 30 дней" },
	{ "Бан аккаунта", function()
		AT.ConfirmCmd(".ban account " .. (AT.lastPlayerInput or "ник") .. " 30 Забанен администратором",
			"Забанить аккаунт на 30 дней?")
	end, AT.BTN_W, 3, "Бан аккаунта на 30 дней" },
	{ "Разбан персонажа", function()
		AT.ConfirmCmd(".unban character " .. (AT.lastPlayerInput or "ник"), "Снять бан с персонажа?")
	end, AT.BTN_W, 3, "Снять бан с персонажа" },
	{ "Разбан аккаунта", function()
		AT.ConfirmCmd(".unban account " .. (AT.lastPlayerInput or "ник"), "Снять бан с аккаунта?")
	end, AT.BTN_W, 3, "Снять бан с аккаунта" },
}, y - 4)

y = AT.FormRow(p, y - 4, "Бан аккаунта (после ника):", function(t)
	return ".ban account " .. (AT.lastPlayerInput or "ник") .. " " .. t
end)

y = AT.FormRow(p, y, "Инфо о бане персонажа:", function(t) return ".ban info character " .. t end)
y = AT.FormRow(p, y, "Отправить предмет:", function(t)
	-- формат: ник "тема" "текст" itemid:кол-во
	return ".send items " .. t
end)

--===========================================================================
-- Обслуживание
--===========================================================================
y = AT.MakeSection(p, "Обслуживание", y - 6)

y = AT.FlowButtons(p, {
	{ "Сохранить всё",  ".saveall", AT.BTN_W, 2, "Сохранить всех персонажей в БД" },
	{ "Сохранить себя", ".save",    AT.BTN_W, 2, "Сохранить своего персонажа" },
	{ "Reload config",  ".reload config", AT.BTN_W, 3, "Перечитать конфиги ядра" },
	{ "Отмена выкл.",   ".server shutdown cancel", AT.BTN_W, 2, "Отменить выключение" },
	{ "Отмена рестарта", ".server restart cancel", AT.BTN_W, 2, "Отменить перезапуск" },
}, y)

--===========================================================================
-- Опасное
--===========================================================================
y = AT.MakeSection(p, "Опасное (с подтверждением)", y - 6)

y = AT.FlowButtons(p, {
	{ "Рестарт 60с", function()
		AT.ConfirmCmd(".server restart 60", "Перезапустить сервер через 60 секунд?")
	end, AT.BTN_W, 3, "Перезапуск через 60 секунд" },
	{ "Рестарт 5м", function()
		AT.ConfirmCmd(".server restart 300", "Перезапустить сервер через 5 минут?")
	end, AT.BTN_W, 3, "Перезапуск через 5 минут" },
	{ "Выкл 60с", function()
		AT.ConfirmCmd(".server shutdown 60", "Выключить сервер через 60 секунд?")
	end, AT.BTN_W, 3, "Выключение через 60 секунд" },
	{ "Выкл 5м", function()
		AT.ConfirmCmd(".server shutdown 300", "Выключить сервер через 5 минут?")
	end, AT.BTN_W, 3, "Выключение через 5 минут" },
	{ "Создать аккаунт", function()
		local info = AT.lastAccountInput or "логин:пароль"
		AT.ConfirmCmd(".account create " .. info, "Создать аккаунт «" .. info .. "»?")
	end, AT.BTN_W, 3, "Создать аккаунт (логин:пароль из поля ниже)" },
}, y)

--===========================================================================
-- Сообщения игрокам
--===========================================================================
y = AT.MakeSection(p, "Сообщения игрокам", y - 6)

y = AT.FormRow(p, y, "Анонс (всем):", function(t) return ".announce " .. t end)
y = AT.FormRow(p, y, "MOTD:", function(t) return ".server set motd " .. t end)
y = AT.FormRow(p, y, "Выключить (сек):", function(t) return ".server shutdown " .. t end)
y = AT.FormRow(p, y, "Аккаунт (логин:пароль):", function(t)
	AT.lastAccountInput = t
	return ".account create " .. t
end)
AT.FormRow(p, y, "Сменить пароль (логин:старый:новый):", function(t)
	return ".account password " .. t
end)
